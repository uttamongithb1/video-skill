#!/usr/bin/env bash
# scenes.sh — every scene in the reel, reproducibly, in one file.
#
# Regenerating is safe: nothing is hand-tuned inside a composition
# (that is what the token block is for), so this file is the single
# source of the picture. Edit it, re-run it, re-render.
#
# THE SHAPE OF A GOOD SET
#   * one scene per VO section, same order as sections.json
#   * field must differ from the previous scene (prepare.py fails if it does not)
#   * a different pose in every scene, matched to the beat
#   * archetype by beat: card-led = proof, stat-led = a number, type-led = a statement
#   * hero 1-3 words, chip 3-6 words, the card carries the detail
#   * scene 1 is the cover (new_scene sets data-cover="1"), so it must look finished at frame 0
set -e
cd "$(dirname "$0")"
NS="python3 scripts/new_scene.py --force"

# ---- replace everything below with your own beats -------------------------------------------------
# Example beats (auto-generated by orchestrator from your voice script):
# $NS --n 1 --name hook     --arch card-led --field accent     --pose p1_shrug.png \
#     --kicker "AI FOR COLLEGE" --hero "SAME RESUME?" --chip "har company mein bhej rahe ho?" \
#     --card-title "applied / 12 companies" --card-meta "this week" \
#     --card-body @components/file-list.html
#
# $NS --n 2 --name animation --arch card-led --field ground --pose p2_facepalm.png \
#     --kicker "AI FOR COLLEGE" --hero "TOR ARCHITECTURE" --chip "verified path" \
#     --card-body "[SVG diagram embedded]"
#
# $NS --n 3 --name body     --arch card-led --field ink --pose p3_present.png \
#     --kicker "AI FOR COLLEGE" --hero "CUSTOMIZE KARO" --chip "job ke according"
#
# $NS --n 4 --name cta      --arch type-led --field accent --pose p7_cta.png \
#     --kicker "AI FOR COLLEGE" --hero "GET SHORTLISTED" --chip "customize per company"
#
# ---- always last: tokens into every composition, then the root ------------------------------------
python3 scripts/prepare.py
python3 scripts/build_index.py
